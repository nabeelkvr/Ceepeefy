export const registerDynamicArtist = (artist) => {
  if (!artist || !artist.name) return null;
  const cleanName = artist.name.trim();
  const slug = cleanName.toLowerCase().replace(/[^a-z0-9]/g, "-");
  const id = artist.id || `artist-${slug}`;
  const profile = {
    id,
    name: cleanName,
    role: artist.role || "Artist",
    genre: artist.genre || "Music",
    category: "Trending Now",
    categories: ["Trending Now"],
    followers: artist.followers || "14.2M",
    monthlyListeners: artist.monthlyListeners || "32,800,000",
    avatar: artist.avatar || artist.image || "https://images.unsplash.com/photo-1511671782779-c97d3d27a1d4?w=600&auto=format&fit=crop&q=80",
    bio: artist.bio || `${cleanName} is an internationally celebrated recording artist renowned for captivating vocal performances and studio-grade acoustics.`,
    tracks: artist.tracks || []
  };

  dynamicArtistsCache.set(id.toLowerCase(), profile);
  dynamicArtistsCache.set(slug.toLowerCase(), profile);
  dynamicArtistsCache.set(cleanName.toLowerCase(), profile);
  return profile;
};

export const getArtistByIdOrSlug = (idOrSlug) => {
  if (!idOrSlug) return null;
  const raw = String(idOrSlug).trim();
  const clean = decodeURIComponent(raw).trim().toLowerCase();
  const cleanId = clean.replace(/^artist[-_]/, "");
  const slugified = clean.replace(/\s+/g, "-");
  const deslugified = clean.replace(/-/g, " ");

  const match = NOCTURNE_ARTISTS.find((a) => {
    const aId = a.id.toLowerCase();
    const aName = a.name.toLowerCase();
    const aSlug = aName.replace(/\s+/g, "-");
    return (
      aId === clean ||
      aId.replace("artist-", "") === cleanId ||
      aName === clean ||
      aName === deslugified ||
      aSlug === clean ||
      aSlug === slugified
    );
  });

  if (match) return match;

  // Check dynamic cached artists
  if (dynamicArtistsCache.has(clean)) return dynamicArtistsCache.get(clean);
  if (dynamicArtistsCache.has(cleanId)) return dynamicArtistsCache.get(cleanId);
  if (dynamicArtistsCache.has(slugified)) return dynamicArtistsCache.get(slugified);

  // Synthesize artist profile if user navigates to an artist not yet in the curated list
  const cleanNameForSynth = cleanId.replace(/-/g, " ");
  const formattedName = cleanNameForSynth
    .split(" ")
    .filter(Boolean)
    .map((w) => w.charAt(0).toUpperCase() + w.slice(1))
    .join(" ");

  const cleanSlug = cleanNameForSynth.replace(/\s+/g, "-");

  return {
    id: `artist-${cleanSlug}`,
    name: formattedName,
    role: "Artist",
    genre: "Music",
    category: "Trending Now",
    categories: ["Trending Now"],
    followers: "14.2M",
    monthlyListeners: "32,800,000",
    avatar: "https://images.unsplash.com/photo-1511671782779-c97d3d27a1d4?w=600&auto=format&fit=crop&q=80",
    bio: `${formattedName} is an internationally celebrated recording artist renowned for captivating vocal performances and studio-grade acoustics.`
  };
};

/**
 * Deterministically shuffles an artist array based on a daily seed or date string
 */
export const getDailyRotatedArtists = (artists, seed) => {
  if (!artists || artists.length <= 1) return artists;
  let currentSeed = typeof seed === "number" ? seed : 0;
  if (typeof seed === "string") {
    let hash = 0;
    for (let i = 0; i < seed.length; i++) {
      hash = (hash << 5) - hash + seed.charCodeAt(i);
      hash |= 0;
    }
    currentSeed = Math.abs(hash);
  }

  const result = [...artists];
  const random = () => {
    currentSeed = (currentSeed * 1664525 + 1013904223) % 4294967296;
    return currentSeed / 4294967296;
  };

  for (let i = result.length - 1; i > 0; i--) {
    const j = Math.floor(random() * (i + 1));
    [result[i], result[j]] = [result[j], result[i]];
  }
  return result;
};

export const getArtistsByCategory = (
  category = "Trending Now",
  dateSeed = null,
  liveArtists = [],
  limit = 12
) => {
  let baseList;
  if (!category || category === "All") {
    baseList = [...NOCTURNE_ARTISTS];
  } else {
    baseList = NOCTURNE_ARTISTS.filter((a) => {
      if (Array.isArray(a.categories)) {
        return a.categories.includes(category);
      }
      return a.category === category || a.genre?.toLowerCase().includes(category.toLowerCase());
    });
  }

  // Merge live trending artists if provided
  if (Array.isArray(liveArtists) && liveArtists.length > 0) {
    const existingNames = new Set(baseList.map((a) => a.name.toLowerCase()));
    const matchingLive = liveArtists.filter((la) => {
      if (!la?.name || existingNames.has(la.name.toLowerCase())) return false;
      if (category === "Trending Now") return true;
      if (Array.isArray(la.categories)) {
        return la.categories.includes(category);
      }
      return la.category === category || la.genre?.toLowerCase().includes(category.toLowerCase());
    });

    matchingLive.forEach((la) => registerDynamicArtist(la));
    baseList = [...matchingLive, ...baseList];
  }

  if (dateSeed !== null && dateSeed !== undefined) {
    const rotated = getDailyRotatedArtists(baseList, dateSeed);
    return limit ? rotated.slice(0, limit) : rotated;
  }

  return limit ? baseList.slice(0, limit) : baseList;
};


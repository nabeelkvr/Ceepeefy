// Helper maps for instantaneous lookups
export const GENRE_MAP = new Map(CURATED_GENRES.map((g) => [g.id, g]));
export const GENRE_NAME_MAP = new Map(CURATED_GENRES.map((g) => [g.name.toLowerCase(), g]));

export function getGenreById(id) {
  if (!id) return null;
  return GENRE_MAP.get(id) || null;
}

export function getGenreByName(name) {
  if (!name) return null;
  const clean = name.toLowerCase().trim();
  if (GENRE_NAME_MAP.has(clean)) return GENRE_NAME_MAP.get(clean);
  for (const g of CURATED_GENRES) {
    if (clean.includes(g.name.toLowerCase()) || g.name.toLowerCase().includes(clean)) {
      return g;
    }
  }
  return null;
}
